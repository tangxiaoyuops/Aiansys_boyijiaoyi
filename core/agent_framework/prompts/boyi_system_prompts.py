# 博弈分析核心概念
GAME_THEORY_CONCEPTS = """
# 博弈分析核心概念

## 1. O点（原始低点）

**定义**：上一轮熊市结束时的最低点，本轮上升趋势的原始低点

**识别方法**：
- 历史价格最低点
- 成交量极度萎缩
- 市场情绪极度悲观
- 技术指标背离

**重要性**：
- 一阶段的起点
- 趋势力量在O点初现时微弱，仅能防止股价跌破
- O点不破，趋势存在

---

## 2. 情绪比例关系

**核心原理**：
股票的涨跌波动过程可以改变事先判定的结果

**应用原则**：
1. 较为好看的出货 + 非常难看的洗盘 = 后市看涨
2. 较为难看的洗盘后 + 直接跟非常好看的出货 = 后市看跌

**量化方法**：
- 出货好看度：阳线数量、涨幅、成交量
- 洗盘难看度：阴线数量、跌幅、破位情况

**重要性**：
情绪比例关系是精英投资者与普通高手的差别所在

---

## 3. 牛股结构

### 一阶段牛股结构
- 情绪比例关系合格后继续洗盘
- 形成后股票大概率上涨，涨幅可观
- 操作：情绪比例关系合格后，下跌时买入底仓

### 二阶段牛股结构
- 上涨过程中没有明显的大规模出货高点
- 上涨过程中没有形成多方锚定
- 下跌过程中形成了空方锚定
- 严格控制上涨时的憧憬情绪，洗盘时制造绝望情绪

---

## 4. 锚定理论

### 多方锚定
**定义**：主力将散户思维锚定在多头阵营

**特征**：
- 散户一致看多
- 阳线个头越来越大
- 散户越来越愿意买入

**应用**：
- 多方锚定形成 → 买入信号
- 多方锚定被破坏 → 空头方向运行是加仓信号

### 空方锚定
**定义**：主力将散户思维固定在空方阵营

**方法**：
- 下跌初期恐怖性下跌
- 持续补空锚，唤起上一轮下跌的恐惧感

**目的**：
在上涨行情中保持散户的空头思维，防止散户进场

---

## 5. 洗盘理论

### 洗盘定义
主力通过控制股票走势，使散户止盈或止损离场

**核心**：里面的散户都出去，外面的散户别进来

### 洗盘公式
洗盘效果 = 恐惧程度 × 焦虑程度 × 场内散户数量

- **恐惧程度**：走势难看程度，形态越恐惧效果越好
- **焦虑程度**：持有时间越长，焦虑越大
- **场内散户数量**：场内散户越少，效果越好

### 洗盘类型

#### K线组合洗盘
- 通过几根K线打破上涨形态
- 第一根：告诉散户有压力
- 第二根：继续提醒有阻力
- 第三根：确认上涨乏力

#### 波段洗盘
- 通过一段时间下跌打破上涨形态
- 特征：没有分水岭高点，下跌过程中没有钩子
- 需要借助大盘下跌

### 洗盘识别要点
- 价格特征：下跌但未破关键支撑
- 成交量特征：缩量下跌
- 形态特征：难看但未破坏趋势
- 情绪特征：散户恐慌但主力未出货

---

## 6. 出货识别

### 大规模出货
**特征**：
- 洗盘时间：一年以上
- 必须打广告，吸引所有散户
- 针对五大门派：突破派、抄底派、激进派、趋势派、博弈派

**操作**：识别后一年内不做中长线，仅做短线

### 中等规模出货
**特征**：
- 洗盘时间：3-6个月
- 只针对突破派

**操作**：洗盘三个月后直接上涨，底仓5%，加仓10-15%

### 小规模出货
**特征**：
- 洗盘时间：三个月以内
- 买入的人少且种类少

**操作**：洗盘过程中逐步买入，持续加仓
"""

